// TestWorldAttack_NumericCoordOrder asserts the emitted tile records are in
// STRICTLY-ASCENDING NUMERIC coord order (X then Y) -- and specifically that a
// double-digit X sorts AFTER a single-digit X (the lexical-vs-numeric gap a
// prior finding caught: "10" < "2" lexically).
func TestWorldAttack_NumericCoordOrder(t *testing.T) {
	orig := freshW()
	injectRichWorld(t, orig)
	snap, err := orig.w.snapshotForSave()
	ckErrW(t, err)
	if len(snap.tiles) < 3 {
		t.Fatalf("need >=3 tiles to test order, got %d", len(snap.tiles))
	}
	sawX10 := false
	sawX2 := false
	var x10Idx, x2LastIdx int
	for i := 1; i < len(snap.tiles); i++ {
		prev, cur := snap.tiles[i-1].Coord, snap.tiles[i].Coord
		if !lessTileCoord(prev, cur) {
			t.Fatalf("tiles not strictly numeric-ascending at %d: %v then %v", i, prev, cur)
		}
	}
	for i, tw := range snap.tiles {
		if tw.Coord.X == 2 {
			sawX2 = true
			x2LastIdx = i
		}
		if tw.Coord.X == 10 {
			sawX10 = true
			x10Idx = i
		}
	}
	if !sawX2 || !sawX10 {
		t.Fatalf("expected both X=2 and X=10 tiles present (numeric-vs-lexical probe)")
	}
	if x10Idx <= x2LastIdx {
		t.Fatalf("numeric order broken: X=10 tile at idx %d is not after the last X=2 tile at idx %d (lexical sort would put X=10 first)", x10Idx, x2LastIdx)
	}
}

