// Round-trip determinism (the bar) + the DERIVED-recompute KEY test.
// ---------------------------------------------------------------------------

func TestWorldParticipant_RoundTrip(t *testing.T) {
	orig := freshW()
	injectRichWorld(t, orig)

	root := saveIntoW(t, orig, "orig")

	reloaded := freshW()
	loadIntoW(t, root, reloaded, "reloaded")
	compareWorld(t, orig.w, reloaded.w, "post-load")

	// Continue identical, deterministic durable operations on BOTH and assert
	// they stay equal: a divergent restore would surface the moment new work
	// builds on it.
	continueWorld(t, orig)
	continueWorld(t, reloaded)
	compareWorld(t, orig.w, reloaded.w, "post-continue")
}

func continueWorld(t *testing.T, a *WorldAPI) {
	t.Helper()
	purchaseW(t, a, TileCoord{X: 15, Y: 15}, 999)
	setCellW(t, a, TileCoord{X: 15, Y: 15}, ownedCellSpec{CellLocal{Row: 9, Col: 9}, 55, ZoningCommercial, 77})
	ckErrW(t, a.Prospect(TileCoord{X: 1, Y: 1}, "cont"))
}

// TestWorldParticipant_DerivedRecomputesAfterLoad is the inc8 KEY test: after
// a round trip into a FRESH world, the DERIVED terrain (elevation/slope/
// surface) and the DERIVED landValue RECOMPUTE to the same values as the
// original — proving it is correct NOT to serialize them (they are pure
// functions of the restored coord + startHeight), and that the durable
// ownership/zoning/structure state restored exactly.
func TestWorldParticipant_DerivedRecomputesAfterLoad(t *testing.T) {
	orig := freshW()
	injectRichWorld(t, orig)
	root := saveIntoW(t, orig, "orig")

	reloaded := freshW()
	loadIntoW(t, root, reloaded, "reloaded")

	// Every cell of an owned tile: terrain + landValue + durable fields must
	// match between orig and reloaded, cell for cell.
	for _, c := range []TileCoord{{X: 2, Y: 5}, {X: 2, Y: 9}, {X: 10, Y: 3}} {
		oc, err := orig.TileCells(c, "cmp-o")
		ckErrW(t, err)
		rc, err := reloaded.TileCells(c, "cmp-r")
		ckErrW(t, err)
		if len(oc) != len(rc) {
			t.Fatalf("tile %v cell count %d != %d", c, len(oc), len(rc))
		}
		for i := range oc {
			if oc[i] != rc[i] {
				t.Fatalf("tile %v cell %d differs after load:\n orig=%+v\n reld=%+v", c, i, oc[i], rc[i])
			}
		}
		// LandValue must be non-zero somewhere (proves it recomputed, not left zero).
		anyLV := false
		for i := range rc {
			if rc[i].LandValue != 0 {
				anyLV = true
				break
			}
		}
		if !anyLV {
			t.Fatalf("tile %v: reloaded landValue is all zero -- DERIVED recompute did not run", c)
		}
	}

	// The start tile's terrain came from the imported heightmap; it must
	// regenerate identically from the restored startHeight.
	oStart, err := orig.CellAt(startCoordFixture, CellLocal{Row: 100, Col: 100}, "s-o")
	ckErrW(t, err)
	rStart, err := reloaded.CellAt(startCoordFixture, CellLocal{Row: 100, Col: 100}, "s-r")
	ckErrW(t, err)
	if oStart != rStart {
		t.Fatalf("start-tile cell differs after load:\n orig=%+v\n reld=%+v", oStart, rStart)
	}

	// The prove-can-fail guard for this test: if landValue were WRONGLY
	// serialized-and-restored from a stale value rather than recomputed, a
	// re-import against different terrain would strand it — but that is the
	// BUG-066 path, already covered. Here we simply assert full durable parity.
	compareWorld(t, orig.w, reloaded.w, "derived-recompute")
}

// TestWorldParticipant_ProveCanFail mutates each durable field family on one
// pristine reload and asserts it diverges from a second pristine reload of the
// SAME bytes -- proving the comparison is discriminating for every field.
func TestWorldParticipant_ProveCanFail(t *testing.T) {
	orig := freshW()
	injectRichWorld(t, orig)
	root := saveIntoW(t, orig, "orig")

	cases := []struct {
		name   string
		mutate func(a *WorldAPI)
	}{
		{"milestoneTier", func(a *WorldAPI) { a.w.mu.Lock(); a.w.milestoneTier++; a.w.mu.Unlock() }},
		{"startCoord", func(a *WorldAPI) { a.w.mu.Lock(); a.w.startCoord.X++; a.w.mu.Unlock() }},
		{"startHeight", func(a *WorldAPI) { a.w.mu.Lock(); a.w.startHeight[0][0] += 100; a.w.mu.Unlock() }},
		{"tile.ownerID", func(a *WorldAPI) { a.w.mu.Lock(); a.w.tiles[TileCoord{X: 2, Y: 5}].ownerID = 0; a.w.mu.Unlock() }},
		{"tile.owned", func(a *WorldAPI) { a.w.mu.Lock(); a.w.tiles[TileCoord{X: 2, Y: 5}].owned = false; a.w.mu.Unlock() }},
		{"tile.prospected", func(a *WorldAPI) { a.w.mu.Lock(); a.w.tiles[TileCoord{X: 4, Y: 4}].prospected = false; a.w.mu.Unlock() }},
		{"sim.owner", func(a *WorldAPI) {
			a.w.mu.Lock()
			a.w.tiles[TileCoord{X: 2, Y: 5}].sim.owner[localIndex(1, 1)] = 0
			a.w.mu.Unlock()
		}},
		{"sim.zoning", func(a *WorldAPI) {
			a.w.mu.Lock()
			a.w.tiles[TileCoord{X: 2, Y: 9}].sim.zoning[localIndex(6, 2)] = ZoningNone
			a.w.mu.Unlock()
		}},
		{"sim.structureRef", func(a *WorldAPI) {
			a.w.mu.Lock()
			a.w.tiles[TileCoord{X: 10, Y: 3}].sim.structureRef[localIndex(5, 5)] = 0
			a.w.mu.Unlock()
		}},
		{"drop-tile", func(a *WorldAPI) { a.w.mu.Lock(); delete(a.w.tiles, TileCoord{X: 2, Y: 9}); a.w.mu.Unlock() }},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			mutated := freshW()
			loadIntoW(t, root, mutated, "mutated")
			pristine := freshW()
			loadIntoW(t, root, pristine, "pristine")
			compareWorld(t, mutated.w, pristine.w, "pre-mutation")
			c.mutate(mutated)
			if worldStatesEqual(mutated.w, pristine.w) {
				t.Fatalf("prove-can-fail: mutating %s did not diverge from a pristine reload -- the field may be dropped or the compare is blind to it", c.name)
			}
		})
	}
}

