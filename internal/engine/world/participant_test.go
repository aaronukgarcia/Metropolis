// injectRichWorld builds a distinct-non-zero durable world: a non-nil
// imported heightmap, a distinct milestone tier, three OWNED tiles at
// distinct non-zero coords (chosen so numeric X ordering differs from lexical
// — X=2 and X=10), each with several distinct owned cells; one
// PROSPECTED-but-unowned tile; and one QUERY-ONLY tile that must NOT be
// serialized (owned=false, prospected=false).
func injectRichWorld(t *testing.T, a *WorldAPI) {
	t.Helper()
	w := a.w
	w.mu.Lock()
	w.milestoneTier = 4
	w.startHeight = slopedHeights(TileSizeCells, 37) // distinct non-flat 200x200 import
	w.mu.Unlock()

	purchaseW(t, a, TileCoord{X: 2, Y: 5}, 100)
	purchaseW(t, a, TileCoord{X: 2, Y: 9}, 200)  // same X, higher Y — tests tie-break by Y
	purchaseW(t, a, TileCoord{X: 10, Y: 3}, 300) // X=10 > X=2 numerically but "10" < "2" lexically

	setCellW(t, a, TileCoord{X: 2, Y: 5}, ownedCellSpec{CellLocal{Row: 1, Col: 1}, 7, ZoningResidential, 11})
	setCellW(t, a, TileCoord{X: 2, Y: 5}, ownedCellSpec{CellLocal{Row: 3, Col: 4}, 9, ZoningCommercial, 13})
	setCellW(t, a, TileCoord{X: 2, Y: 9}, ownedCellSpec{CellLocal{Row: 2, Col: 6}, 21, ZoningIndustrial, 41})
	setCellW(t, a, TileCoord{X: 10, Y: 3}, ownedCellSpec{CellLocal{Row: 5, Col: 5}, 33, ZoningAgricultural, 61})

	// A prospected-but-unowned tile (durable prospect flag, no simGrid).
	ckErrW(t, a.Prospect(TileCoord{X: 4, Y: 4}, "setup"))

	// A query-only tile: terrain gets generated but it is neither owned nor
	// prospected, so it MUST be absent from the save.
	if _, err := a.TileAt(TileCoord{X: 20, Y: 20}, "setup"); err != nil {
		t.Fatalf("query-only TileAt: %v", err)
	}
}

// injectManyTiles forces MANY owned + prospected tiles across a wide coord
// range (X and Y both spanning single- and double-digit values) so a
// lexical-not-numeric sort, or any unsorted emission, would reorder them.
func injectManyTiles(t *testing.T, a *WorldAPI) {
	t.Helper()
	w := a.w
	w.mu.Lock()
	w.milestoneTier = 6
	w.startHeight = slopedHeights(TileSizeCells, 51)
	w.mu.Unlock()

	// 25 owned tiles at (x,y) over a range that mixes 1- and 2-digit coords.
	n := 0
	for x := 0; x < 5; x++ {
		for y := 0; y < 5; y++ {
			c := TileCoord{X: x*3 + 1, Y: y*4 + 2} // X in {1,4,7,10,13}, Y in {2,6,10,14,18}
			purchaseW(t, a, c, uint32(1000+n))
			setCellW(t, a, c, ownedCellSpec{CellLocal{Row: n % 7, Col: (n + 1) % 11}, uint32(n + 1), Zoning(uint8(n % 5)), uint32(n*3 + 5)})
			n++
		}
	}
	// A spread of prospected-only tiles.
	for x := 0; x < 6; x++ {
		ckErrW(t, a.Prospect(TileCoord{X: x*4 + 2, Y: 25}, "setup"))
	}
}

// ---------------------------------------------------------------------------
// Comparison + save/load drivers. Durable equality is defined as equality of
// the production snapshot (meta + numeric-sorted owned-or-prospected tiles
// with their durable columns) — exactly the serialized set.
// ---------------------------------------------------------------------------

func compareWorld(t *testing.T, a, b *World, label string) {
	t.Helper()
	sa, err := a.snapshotForSave()
	ckErrW(t, err)
	sb, err := b.snapshotForSave()
	ckErrW(t, err)
	if !reflect.DeepEqual(sa.meta, sb.meta) {
		t.Fatalf("%s: meta mismatch:\n a=%+v\n b=%+v", label, dumpMeta(sa.meta), dumpMeta(sb.meta))
	}
	if len(sa.tiles) != len(sb.tiles) {
		t.Fatalf("%s: durable tile count %d != %d", label, len(sa.tiles), len(sb.tiles))
	}
	for i := range sa.tiles {
		if !reflect.DeepEqual(sa.tiles[i], sb.tiles[i]) {
			t.Fatalf("%s: tile[%d] mismatch: coord a=%v b=%v owned a=%v b=%v ownerID a=%v b=%v prospected a=%v b=%v (columns differ: %v)",
				label, i, sa.tiles[i].Coord, sb.tiles[i].Coord, sa.tiles[i].Owned, sb.tiles[i].Owned,
				sa.tiles[i].OwnerID, sb.tiles[i].OwnerID, sa.tiles[i].Prospected, sb.tiles[i].Prospected,
				!reflect.DeepEqual(sa.tiles[i].Owner, sb.tiles[i].Owner) || !reflect.DeepEqual(sa.tiles[i].Zoning, sb.tiles[i].Zoning) || !reflect.DeepEqual(sa.tiles[i].StructureRef, sb.tiles[i].StructureRef))
		}
	}
}

// dumpMeta summarises a meta wire without printing the whole 200x200 map.
func dumpMeta(m worldMetaWire) string {
	rows := len(m.StartHeight)
	cols := 0
	if rows > 0 {
		cols = len(m.StartHeight[0])
	}
	return "startCoord=" + itoa(m.StartCoord.X) + "," + itoa(m.StartCoord.Y) +
		" tier=" + itoa(m.MilestoneTier) + " height=" + itoa(rows) + "x" + itoa(cols)
}

func worldStatesEqual(a, b *World) bool {
	sa, ea := a.snapshotForSave()
	sb, eb := b.snapshotForSave()
	if ea != nil || eb != nil {
		return false
	}
	return reflect.DeepEqual(sa, sb)
}

