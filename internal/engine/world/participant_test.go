func TestWorldAttack_LoadIntoNonEmptyFullyReplaces(t *testing.T) {
	orig := freshW()
	injectRichWorld(t, orig)
	root := saveIntoW(t, orig, "orig")

	// Pre-populate the target with a DIFFERENT, larger state including a GHOST
	// owned tile the saved state never touches.
	target := freshW()
	injectManyTiles(t, target)
	const ghostX, ghostY = 13, 18 // present in injectManyTiles, absent from injectRichWorld
	target.w.mu.RLock()
	_, ghostPresent := target.w.tiles[TileCoord{X: ghostX, Y: ghostY}]
	target.w.mu.RUnlock()
	if !ghostPresent {
		t.Fatalf("test setup: ghost tile not present on target pre-load")
	}
	orig.w.mu.RLock()
	_, ghostInOrig := orig.w.tiles[TileCoord{X: ghostX, Y: ghostY}]
	orig.w.mu.RUnlock()
	if ghostInOrig {
		t.Fatalf("test setup: saved state unexpectedly holds the ghost tile")
	}

	loadIntoW(t, root, target, "target")

	target.w.mu.RLock()
	gt := target.w.tiles[TileCoord{X: ghostX, Y: ghostY}]
	target.w.mu.RUnlock()
	if gt != nil && (gt.owned || gt.prospected) {
		t.Fatalf("ghost tile survived load as durable -- Handler merged instead of replacing")
	}
	if got, want := durableTileCount(t, target), durableTileCount(t, orig); got != want {
		t.Fatalf("durable tile count %d != saved %d -- merge, not replace", got, want)
	}
	compareWorld(t, orig.w, target.w, "load-into-nonempty")
}

