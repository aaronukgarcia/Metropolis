function board(buildings, population = 0) {
  const base = initialState();
  let maxId = 0;
  for (const bb of buildings) if (bb.id > maxId) maxId = bb.id;
  return { ...base, unlockedAll: true, buildings, nextId: maxId + 1, roadNotice: null, population };
}
