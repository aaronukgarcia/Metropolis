test('round2: the doc\'s literal AC-5 (per-CLASS totals identical) is UNSATISFIABLE on a differentiated fixture, while the GRAND TOTAL conserves exactly', () => {
  // The point of this pin is to stop a future increment "restoring" the
  // doc's per-class invariant: per-tile differentiation is the whole
  // feature, so per-class totals MUST diverge from the population-keyed
  // city computation. Measured here, not asserted from memory.
  const s = board([b(1, 'res_hut', 80, 80), b(2, 'rail', 80, 81), b(3, 'res_hut', 600, 600)], 50);
  const tiles = demandForecastOf(s);
  assert.ok(tiles.length >= 2, 'fixture precondition: at least two demand tiles');
  const perTile = perTileLocalModeShareOf(s);
  const cityRow = modeShareOf(ladderPointOf(s));
  const ids = Object.keys(cityRow);
  const pt = {}, cw = {};
  for (const id of ids) { pt[id] = 0; cw[id] = 0; }
  let trips = 0;
  for (const t of tiles) {
    const v = perTile.get(`${t.x},${t.y}`);
    trips += t.personTrips;
    for (const id of ids) { pt[id] += (v[id] ?? 0) * t.personTrips; cw[id] += (cityRow[id] ?? 0) * t.personTrips; }
  }
  const worst = Math.max(...ids.map((id) => Math.abs(pt[id] - cw[id])));
  assert.ok(worst > 1e-9, `per-class divergence must be REAL (got ${worst}) — if this ever goes to zero the per-tile split has stopped differentiating`);
  let sPt = 0, sCw = 0;
  for (const id of ids) { sPt += pt[id]; sCw += cw[id]; }
  assert.ok(Math.abs(sPt - trips) < 1e-9, `per-tile grand total ${sPt} must equal person-trips ${trips}`);
  assert.ok(Math.abs(sCw - trips) < 1e-9, `city-wide grand total ${sCw} must equal person-trips ${trips}`);
});

