test('round: at IDENTICAL population, building a rail line moves the realised city-wide split while the city-level split does not move at all', () => {
  const without = board([b(1, 'res_block', 10, 10), b(2, 'res_block', 40, 40)], 200);
  const withRail = board([b(1, 'res_block', 10, 10), b(2, 'res_block', 40, 40), b(3, 'rail', 10, 11)], 200);
  const a = realisedCityWideModeShareOf(without);
  const c = realisedCityWideModeShareOf(withRail);
  assert.notDeepEqual(a, c, 'the realised split must respond to built infrastructure — otherwise inc9 re-coupling is still a population bonus');
  assert.ok(c.car < a.car, `car share must fall with rail access (${a.car} -> ${c.car})`);
  assert.ok(c.bus > a.bus, `bus share must rise with rail access (${a.bus} -> ${c.bus})`);
  // The control: the OLD population-keyed vector is identical in both cities.
  assert.deepEqual(modeShareOf(ladderPointOf(without)), modeShareOf(ladderPointOf(withRail)));
  // And the access band actually differs (not a coincidental numeric shift).
  assert.equal(tileLocalAccessBandOf(without).get('10,10'), 'local_access_none');
  assert.equal(tileLocalAccessBandOf(withRail).get('10,10'), 'local_access_medium');
});

